function dist2D(a: [number, number], b: [number, number]): number {
  const dx = a[0] - b[0];
  const dz = a[1] - b[1];
  return Math.sqrt(dx * dx + dz * dz);
}

function findNearestRoadNode(x: number, z: number): string {
  let bestId = 'n_c_main';
  let bestDist = Infinity;
  for (const node of Object.values(ROAD_GRAPH)) {
    const d = dist2D([x, z], node.pos);
    if (d < bestDist) {
      bestDist = d;
      bestId = node.id;
    }
  }
  return bestId;
}

function findShortestRoadPath(startGraphId: string, endGraphId: string): [number, number][] {
  if (startGraphId === endGraphId) {
    return [ROAD_GRAPH[startGraphId].pos];
  }
  const dist: Record<string, number> = {};
  const prev: Record<string, string | null> = {};
  const unvisited = new Set<string>(Object.keys(ROAD_GRAPH));

  for (const id of unvisited) {
    dist[id] = Infinity;
    prev[id] = null;
  }
  dist[startGraphId] = 0;

  while (unvisited.size > 0) {
    let u: string | null = null;
    let smallest = Infinity;
    for (const id of unvisited) {
      if (dist[id] < smallest) {
        smallest = dist[id];
        u = id;
      }
    }
    if (!u || u === endGraphId) break;
    unvisited.delete(u);

    const nodeU = ROAD_GRAPH[u];
    for (const v of nodeU.neighbors) {
      if (!unvisited.has(v)) continue;
      const alt = dist[u] + dist2D(nodeU.pos, ROAD_GRAPH[v].pos);
      if (alt < dist[v]) {
        dist[v] = alt;
        prev[v] = u;
      }
    }
  }

  const path: [number, number][] = [];
  let curr: string | null = endGraphId;
  while (curr) {
    path.unshift(ROAD_GRAPH[curr].pos);
    curr = prev[curr];
  }
  return path;
}

export function computeNavigationRoute(fromId: string, toId: string): NavigationRouteData {
  const fromNode = NAVIGATION_NODES.find((n) => n.id === fromId) || NAVIGATION_NODES[0];
  const toNode = NAVIGATION_NODES.find((n) => n.id === toId) || NAVIGATION_NODES.find((n) => n.id === 'block-12') || NAVIGATION_NODES[1];

  const startRoadId = findNearestRoadNode(fromNode.position[0], fromNode.position[2]);
  const endRoadId = findNearestRoadNode(toNode.position[0], toNode.position[2]);
  const roadWaypoints2D = findShortestRoadPath(startRoadId, endRoadId);

  const routeY = 0.14;
  const waypoints: [number, number, number][] = [
    [fromNode.position[0], routeY, fromNode.position[2]],
    ...roadWaypoints2D.map(([rx, rz]) => [rx, routeY, rz] as [number, number, number]),
    [toNode.position[0], routeY, toNode.position[2]],
  ];

  // Calculate total path distance along segments
  let totalPathUnits = 0;
  for (let i = 1; i < waypoints.length; i++) {
    totalPathUnits += dist2D(
      [waypoints[i - 1][0], waypoints[i - 1][2]],
      [waypoints[i][0], waypoints[i][2]]
    );
  }

  const distanceMeters = Math.max(60, Math.round(totalPathUnits * 16));
  const walkingMinutes = Math.max(1, Math.round(distanceMeters / 78));

  return {
    fromId: fromNode.id,
    toId: toNode.id,
    fromName: fromNode.name,
    toName: toNode.name,
    walkingMinutes,
    distanceMeters,
    crowdLevel: 'Low',
    accessibility: 'Available',
    waypoints,
  };
}

