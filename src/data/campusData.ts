const createParkingSlots = (zonePrefix: string, total: number, occupied: number, reserved: number, ev: number) => {
  const slots = [];
  for (let i = 1; i <= total; i++) {
    const num = `${zonePrefix}-${String(i).padStart(2, '0')}`;
    let status: 'available' | 'occupied' | 'reserved' | 'ev-charging' = 'available';
    if (i <= ev) status = 'ev-charging';
    else if (i <= ev + reserved) status = 'reserved';
    else if (i <= occupied + reserved) status = 'occupied';
    slots.push({
      id: `${zonePrefix.toLowerCase()}-${i}`,
      number: num,
      status,
      vehiclePlate: status === 'occupied' || status === 'ev-charging' ? `TN-22-EV-${100 + i * 7}` : undefined,
      duration: status === 'occupied' || status === 'ev-charging' ? `${(i % 4) + 1}h ${(i * 13) % 60}m` : undefined,
    });
  }
  return slots;
};

