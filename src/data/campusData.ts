// Helper to generate realistic floor breakdown for all 30 VISTAS blocks
function makeFloors(count: number, baseOcc: number, totalRooms: number) {
  const roomsPerFloor = Math.max(2, Math.round(totalRooms / count));
  return Array.from({ length: count }, (_, i) => ({
    level: i + 1,
    name:
      i === 0
        ? 'Ground Atrium & Smart Halls'
        : i === count - 1
        ? 'Upper Research & Seminar Wing'
        : `Floor ${i + 1} Lecture & Lab Wing`,
    occupancy: Math.min(98, Math.max(25, baseOcc + (i % 2 === 0 ? 4 : -5))),
    activeRooms: Math.max(1, roomsPerFloor - 1),
    totalRooms: roomsPerFloor,
    temp: Number((22.0 + (i % 3) * 0.4).toFixed(1)),
  }));
}

